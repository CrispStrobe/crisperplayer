#!/usr/bin/env python3
"""Verify native AAC waveform decoding in the app sandbox, with Brickwright signing."""
import base64
import math
import os
from pathlib import Path
import struct
import subprocess
import sys
import tempfile
import wave

if sys.platform != 'darwin':
    raise SystemExit('This helper requires macOS.')
root = Path(__file__).resolve().parents[1]
with tempfile.TemporaryDirectory(prefix='crisper-aac-fixture-') as temporary:
    source = Path(temporary) / 'tone.wav'
    target = Path(temporary) / 'tone.m4a'
    with wave.open(str(source), 'wb') as output:
        output.setparams((1, 2, 16000, 0, 'NONE', ''))
        output.writeframes(b''.join(struct.pack('<h', int(4000 * math.sin(2 * math.pi * 440 * i / 16000))) for i in range(12 * 16000)))
    subprocess.run(['/usr/bin/afconvert', '-f', 'm4af', '-d', 'aac', '-b', '32000', str(source), str(target)], check=True)
    # The native test writes these generated bytes inside its own sandbox. A
    # direct host /tmp path would correctly be rejected by the Mac app sandbox.
    environment = dict(os.environ, CRISPER_WAVEFORM_BASE64=base64.b64encode(target.read_bytes()).decode())
    raise SystemExit(subprocess.run(['caffeinate', '-diu', sys.executable, 'scripts/macos_local.py', 'test', '--test-file', 'integration_test/waveform_test.dart'], cwd=root, env=environment).returncode)
